/** Nhóm thiết bị theo loại để chọn thông số chính hiển thị */
export type Kind = "camera" | "switch" | "ap" | "nvr";
export function kindOf(category: string): Kind {
  if (/switch/i.test(category)) return "switch";
  if (/access point/i.test(category)) return "ap";
  if (/nvr/i.test(category)) return "nvr";
  return "camera";
}

